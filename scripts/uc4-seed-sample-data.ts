/**
 * Deterministic partner channel for the demo: one designated organisation
 * fails with the exact failureReason the spec requires, everything else
 * succeeds. (container.ts's MockPartnerChannel fails randomly, so the seed
 * builds its own ShareService on top of the real repositories.)
 */
class ScriptedPartnerChannel implements PartnerChannel {
  readonly failing = new Set<string>()

  async send(_report: AnalysisReport, organization: Organization): Promise<void> {
    if (this.failing.has(organization.id)) {
      throw new Error(TIMEOUT_REASON)
    }
  }
}

