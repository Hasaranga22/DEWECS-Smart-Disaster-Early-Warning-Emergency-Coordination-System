import 'dotenv/config'

import type { AnalysisReport } from '@/modules/uc4-analysis/domain/AnalysisReport'
import type { Organization, PartnerChannel } from '@/modules/uc4-analysis/adapters/PartnerChannel'
import type { AuditLogger } from '@/modules/uc4-analysis/adapters/AuditLogger'
import { ShareService } from '@/modules/uc4-analysis/services/ShareService'
import type { Actor } from '@/shared/contracts/types'
import { container, prodClock, prodIdGenerator } from '@/shared/infra/container'
import { prisma } from '@/shared/infra/prisma/client'
import {
  CITIZEN_IDS,
  COLOMBO,
  GAMPAHA,
  KEGALLE,
  ORG_ARMY,
  ORG_DONOR,
  ORG_WV,
  SAMPLE_DMC,
  SHELTER_IDS,
  ensureUc4SampleData,
} from '@/modules/uc4-analysis/seed/ensureUc4SampleData'

const ALL_SECTIONS = ['ALERTS', 'REACH', 'REPORTS', 'SHELTERS', 'SUPPLIES'] as const
const TIMEOUT_REASON = 'Partner gateway timeout - retry or use email fallback'

const actor: Actor = { id: SAMPLE_DMC, role: 'DMC_OFFICIAL', name: 'Sample DMC Official' }

/**
 * Deterministic partner channel for the demo: one designated organisation
 * fails with the exact failureReason the spec requires, everything else
 * succeeds. (container.ts's MockPartnerChannel fails randomly, so the seed
 * builds its own ShareService on top of the real repositories.)
 */
class ScriptedPartnerChannel implements PartnerChannel {
  readonly failing = new Set<string>()

  async send(_report: AnalysisReport, organization: Organization): Promise<void> {
    if (this.failing.has(organization.id)) {
      throw new Error(TIMEOUT_REASON)
    }
  }
}

const auditLogger: AuditLogger = {
  logGeneration: (reportId, actorId) => console.log(`   [audit] report ${reportId} generated by ${actorId}`),
  logFailure: (reason, actorId) => console.log(`   [audit] generation failed (${reason}) by ${actorId}`),
  logShare: (reportId, outcomes, actorId) =>
    console.log(`   [audit] report ${reportId} shared with ${outcomes.length} recipient(s) by ${actorId}`),
}

async function main() {
  console.log('')
  console.log('  UC4  Sample Data Seeding')
  console.log('')

  // ── STEP 0: cleanup — ONLY rows this script owns (idempotent re-runs) ──────
  console.log(' STEP 0: Cleaning previous sample data...')
  const myReports = await prisma.analysisReport.findMany({
    where: { generatedBy: SAMPLE_DMC },
    select: { id: true },
  })
  if (myReports.length > 0) {
    const ids = myReports.map((r) => r.id)
    await prisma.reportShare.deleteMany({ where: { reportId: { in: ids } } })
    await prisma.analysisReport.deleteMany({ where: { generatedBy: SAMPLE_DMC } })
  }
  await prisma.distribution.deleteMany({ where: { actionId: { startsWith: 'sample-action-' } } })
  await prisma.occupancyEvent.deleteMany({ where: { shelterId: { in: SHELTER_IDS } } })
  await prisma.supplyStock.deleteMany({
    where: { organizationId: { in: [ORG_ARMY, ORG_WV, ORG_DONOR] } },
  })
  await prisma.reportAuditEntry.deleteMany({
    where: { report: { localId: { startsWith: 'sample-report-' } } },
  })
  await prisma.groundReport.deleteMany({ where: { localId: { startsWith: 'sample-report-' } } })
  const myAlerts = await prisma.hazardAlert.findMany({
    where: { message: { startsWith: 'Sample UC4 alert' } },
    select: { id: true },
  })
  const myAlertIds = myAlerts.map((a) => a.id)
  if (myAlertIds.length > 0) {
    await prisma.notificationAttempt.deleteMany({ where: { alertId: { in: myAlertIds } } })
    await prisma.alertTargetDistrict.deleteMany({ where: { alertId: { in: myAlertIds } } })
    await prisma.hazardAlert.deleteMany({ where: { id: { in: myAlertIds } } })
  }
  await prisma.citizen.deleteMany({ where: { id: { in: CITIZEN_IDS } } })
  await prisma.shelter.deleteMany({ where: { id: { in: SHELTER_IDS } } })
  console.log('   Cleanup done\n')

  // ── STEP 1: source data (districts, officers, orgs, citizens, alerts, ──────
  //             attempts, ground reports, shelters, stocks) — shared with the
  //             API-route auto-heal path; every block is marker-gated.
  console.log(' STEP 1: Ensuring sample source data...')
  await ensureUc4SampleData()
  console.log('   Districts / officers / orgs / citizens / alerts / attempts')
  console.log('   ground reports / shelters / stocks ready\n')

  // ── STEP 2: generate the 5 sample AnalysisReports via the REAL UC4 service ─
  console.log(' STEP 2: Generating 5 sample analysis reports (SnapshotService)...')
  const snapshotService = container.uc4.snapshotService

  const r1 = await snapshotService.generate(
    {
      from: '2026-08-01T00:00:00.000Z',
      to: '2026-08-31T23:59:59.000Z',
      districtId: KEGALLE,
      includedSections: [...ALL_SECTIONS],
      language: 'EN',
    },
    actor,
  )
  const r2 = await snapshotService.generate(
    {
      from: '2026-08-01T00:00:00.000Z',
      to: '2026-08-31T23:59:59.000Z',
      districtId: KEGALLE,
      hazardType: 'FLOOD',
      includedSections: [...ALL_SECTIONS],
      language: 'EN',
    },
    actor,
  )
  const r3 = await snapshotService.generate(
    {
      from: '2026-08-01T00:00:00.000Z',
      to: '2026-08-31T23:59:59.000Z',
      includedSections: ['ALERTS', 'REACH', 'SUPPLIES'],
      language: 'SI',
    },
    actor,
  )
  const r4 = await snapshotService.generate(
    {
      from: '2026-09-01T00:00:00.000Z',
      to: '2026-09-30T23:59:59.000Z',
      districtId: GAMPAHA,
      hazardType: 'FLOOD',
      includedSections: [...ALL_SECTIONS],
      language: 'TA',
    },
    actor,
  )
  const r5 = await snapshotService.generate(
    {
      from: '2026-01-01T00:00:00.000Z',
      to: '2026-01-31T23:59:59.000Z',
      districtId: COLOMBO,
      includedSections: [...ALL_SECTIONS],
      language: 'EN',
    },
    actor,
  )
  console.log(`   #1 ${r1.id}  Kegalle ALL Aug EN  warning=${r1.warningFlag}`)
  console.log(`   #2 ${r2.id}  Kegalle FLOOD Aug EN  warning=${r2.warningFlag}`)
  console.log(`   #3 ${r3.id}  ALL districts Aug SI  warning=${r3.warningFlag}`)
  console.log(`   #4 ${r4.id}  Gampaha FLOOD Sep TA  warning=${r4.warningFlag}`)
  console.log(`   #5 ${r5.id}  Colombo Jan EN  warning=${r5.warningFlag} (zero activity)\n`)

  // ── STEP 3: shares with deterministic outcomes (real ShareService) ─────────
  console.log(' STEP 3: Sharing reports to partner organisations...')
  const channel = new ScriptedPartnerChannel()
  const shareService = new ShareService(
    container.uc4.snapshotRepository,
    container.uc4.shareLogRepository,
    channel,
    container.uc4.organizationReader,
    auditLogger,
    prodClock,
    prodIdGenerator,
  )

  channel.failing.add(ORG_WV)
  const outcomes1 = await shareService.share(r1.id, [ORG_ARMY, ORG_WV, ORG_DONOR], actor)
  channel.failing.delete(ORG_WV)
  const retry1 = await shareService.share(r1.id, [ORG_WV], actor) // append-only retry (A2/E4)
  const outcomes4 = await shareService.share(r4.id, [ORG_ARMY], actor)

  for (const outcome of [...outcomes1, ...retry1, ...outcomes4]) {
    const detail = outcome.status === 'FAILED' ? ` (${outcome.failureReason})` : ''
    console.log(`   ${outcome.reportId.slice(0, 8)} → ${outcome.organizationName}: ${outcome.status}${detail}`)
  }
  console.log('')

  console.log('   SEEDING COMPLETE')
  console.log('')
  console.log(' Next: run the verifier:')
  console.log('   npx tsx scripts/uc4-verify-demo.ts')
  console.log('')

  await prisma.$disconnect()
}

main().catch((err) => {
  console.error(' Seed failed:', err)
  process.exit(1)
})
